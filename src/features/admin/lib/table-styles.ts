// Shared class strings for the admin tables, so both behave identically.
//
// Why the child selectors: shadcn's <Table> renders its own wrapper
// (`div[data-slot=table-container]`) with a hardcoded `overflow-x-auto`, and that
// wrapper is not reachable through props — `className` lands on the <table>. Two
// consequences we have to fix from the outside:
//
//  1. `overflow-x: auto` makes the wrapper a scroll container on BOTH axes (CSS
//     computes the visible axis to auto), so a `sticky` header inside it has no
//     scrollport to stick to while the PAGE scrolls: the header just scrolls away.
//     Bounding the wrapper's height turns it into the vertical scrollport, and then
//     the header sticks where it should.
//  2. On desktop the horizontal scrollbar was pure noise. The table itself only
//     carries a min-width below `md` (see the tables), so the horizontal overflow
//     now only kicks in on small screens, which is where it earns its keep.
//
// Editing src/components/ui/table.tsx instead would work, but shadcn primitives are
// generated by the CLI and meant to stay upgradeable (see the add-shadcn-component
// skill), so the override lives here.

/**
 * Wrapper around <Table>. A flex column that may shrink (min-h-0), so the inner
 * container ends up as tall as its rows but never taller than the space the page
 * has left — the table body scrolls, the page does not. A fixed `max-h-[65vh]`
 * here was the earlier mistake: 65vh plus the header, toolbar and pager added up to
 * more than the viewport, so BOTH the page and the table body scrolled.
 */
export const TABLE_FRAME =
  "flex min-h-0 flex-col overflow-hidden rounded-lg border [&_[data-slot=table-container]]:min-h-0 [&_[data-slot=table-container]]:overflow-auto";

/**
 * Applied to <TableHeader>. Sticky lives on the `th` cells, not on `thead`:
 * `position: sticky` on `thead` is still unreliable across browsers.
 */
export const STICKY_HEAD = "[&_th]:bg-background [&_th]:sticky [&_th]:top-0 [&_th]:z-10";

/** Table element: scrolls sideways on phones only, fixed columns from `md` up. */
export const RESPONSIVE_TABLE = "min-w-2xl md:min-w-0 md:table-fixed";
